"""Find the requests the sim suite flies, and write them to
config/scenarios.yaml.

    ros2 run mebot_sim find_pairs

Rerun it whenever the layers change: run_suite refuses requests found with
other layer files than the committed ones, whose sha256 is written beside
them. No ROS graph, and nothing is flown. This checkout's planner is built
in this process, on the GPU, with the control planner's config, and is
pushed the worlds the suite plans in, so that cuRobo judges each state as
the stack's planners will; MuJoCo, on the CPU, measures how deep a straight
joint path takes the sim arm into the true shapes. Each search is seeded and
capped and fails naming what it tried, and nothing is written unless every
one succeeds.

  * S1, 3 platform pairs. Start and goal are valid with the floor and the
    platform. The straight joint path between them is blocked with them, and
    clear with the floor alone by the collision activation distance, so that
    a plan without the platform has no reason to leave it. In MuJoCo, with
    the chair empty, that path takes the arm `crossing_mm` or deeper into the
    MEBot, and no deeper than `elsewhere_mm` into anything else (thresholds
    in config/scenarios.yaml).
  * S2, 3 person pairs: the same for the person layer, the floor and the
    platform on, and the stand-in seated upright with its hands in its lap.
  * S3, a start valid with every layer on, its tool beside the chair on the
    arm's own side, and 8 joint goals valid there: 4 with the tool in front
    of the chair and 4 beside it, spread out.
"""

import argparse
import math
import os
import re
import sys
import tempfile

import mujoco
import numpy as np
import yaml

from mebot_sim import scene, stack

PAIRS = 3
# Each pair search: its seed, how many joint vectors it draws, how many pairs
# of the valid ones it tries, how far apart a start and its goal are on the
# joint that moves most (rad: far enough to cross something, near enough to
# stay close to it), how many paths MuJoCo measures at most, and the
# stand-in's posture (None: an empty chair).
PLATFORM = {
    "seed": 11,
    "states": 30000,
    "tries": 6000,
    "apart_rad": (0.8, 2.0),
    "measured": 300,
    "posture": None,
}
PERSON = {
    "seed": 22,
    "states": 400000,
    "tries": 80000,
    "apart_rad": (0.8, 2.2),
    "measured": 600,
    "posture": "upright_lap",
}
# The S3 search: the start is the valid state whose tool is nearest
# `start_tool`, and `per_region` goals have their tool in each region,
# (low, high) in x, y and z: in front of the chair, and beside it on the
# arm's side.
REACHES = {
    "seed": 33,
    "states": 1000000,
    "start_tool": [0.25, -0.35, 0.25],
    "regions": {
        "front": {"x": [0.55, 0.95], "y": [-0.30, 0.65], "z": [0.05, 0.60]},
        "beside": {"x": [-0.30, 0.75], "y": [-0.80, -0.20], "z": [0.00, 0.60]},
    },
    "per_region": 4,
}
STEPS = 96  # states cuRobo judges strictly inside a straight path
STEP_RAD = 0.005  # MuJoCo's step along a path, on the joint that moves most
# The searches keep this far inside the sim arm's joint ranges and the
# planner's limits: the sim arm cannot reach past its ranges, and cuRobo
# bends a path that comes near a limit.
JOINT_MARGIN_RAD = 0.05
BATCH = 16384  # states per call to cuRobo, which bounds its GPU memory
MARKER = (
    "# --- GENERATED by `ros2 run mebot_sim find_pairs` from here to the end: "
    "do not hand-edit ---"
)
GENERATED = ("layers_sha256", "start", "reaches", "platform_pairs", "person_pairs")


def turning(limits):
    """Which joints turn without end: those whose limits, (2, 7), span more
    than a turn, as the planner's own branch shift decides it."""
    return limits[1] - limits[0] > 2 * math.pi + 1e-6


def wrap(start, goal, turns):
    """`goal` with each joint in `turns` moved by whole turns onto the branch
    nearest `start`: the same arm pose, and the goal the planner's branch
    shift would plan to. (7,) or (N, 7) each."""
    out = np.array(goal, dtype=float)
    out[..., turns] = (
        start[..., turns]
        + (out[..., turns] - start[..., turns] + math.pi) % (2 * math.pi)
        - math.pi
    )
    return out


def search_box(model, limits, margin=JOINT_MARGIN_RAD):
    """Where the searches draw joint vectors, (low, high): `margin` inside the
    sim arm's joint ranges in `model` and the planner's `limits`, and within
    [-pi, pi], as the driver reports a joint that turns without end."""
    low, high = limits[0] + margin, limits[1] - margin
    for i, name in enumerate(stack.MUJOCO_JOINTS):
        j = model.joint(name).id
        if model.jnt_limited[j]:
            low[i] = max(low[i], model.jnt_range[j][0] + margin)
            high[i] = min(high[i], model.jnt_range[j][1] - margin)
    return np.maximum(low, -math.pi), np.minimum(high, math.pi)


def straight(start, goal, steps):
    """`steps` states evenly spaced strictly inside each straight joint path
    from `start` to `goal`, (N, 7) each: (N, steps, 7)."""
    s = np.linspace(0.0, 1.0, steps + 2)[1:-1]
    return start[:, None] + s[None, :, None] * (goal - start)[:, None]


def densify(start, goal, step=STEP_RAD):
    """The straight joint path from `start` to `goal`, both included, no
    joint moving more than `step` between two of its states."""
    n = max(1, math.ceil(np.abs(goal - start).max() / step))
    return start + np.linspace(0.0, 1.0, n + 1)[:, None] * (goal - start)


def sample_pairs(rng, pool, count, apart, turns, limits):
    """Up to `count` (starts, goals) of states of `pool`, each goal moved onto
    its start's branch (wrap) and inside `limits`, apart by (low, high) rad on
    the joint that moves most."""
    index = rng.integers(0, len(pool), size=(30 * count, 2))
    index = index[index[:, 0] != index[:, 1]]
    start = pool[index[:, 0]]
    goal = wrap(start, pool[index[:, 1]], turns)
    far = np.abs(goal - start).max(axis=1)
    keep = (
        (far >= apart[0])
        & (far <= apart[1])
        & ((goal >= limits[0]) & (goal <= limits[1])).all(axis=1)
    )
    keep = np.nonzero(keep)[0][:count]
    return start[keep], goal[keep]


def deepest_contacts(model, path):
    """How deep the sim arm, posed in `model` (scene.build) at each state of
    `path`, goes into each contact group: {group: metres}, a group it never
    goes into left out. MuJoCo's contacts at each pose, without physics."""
    d = mujoco.MjData(model)
    qpos = [model.jnt_qposadr[model.joint(name).id] for name in stack.MUJOCO_JOINTS]
    arm, groups = scene.contact_groups(model)
    arm = set(arm.tolist())
    group_of = {int(g): k for k, gs in groups.items() for g in gs}
    deepest = {}
    for q in path:
        d.qpos[qpos] = q
        mujoco.mj_fwdPosition(model, d)
        for i in range(d.ncon):
            contact = d.contact[i]
            a, g = int(contact.geom1), int(contact.geom2)
            if g not in group_of:
                a, g = g, a
            if a in arm and g in group_of and contact.dist < 0:
                group = group_of[g]
                deepest[group] = max(deepest.get(group, 0.0), -float(contact.dist))
    return deepest


class Planner:
    """This checkout's planner, built in this process with the control
    planner's config, and what the searches ask it of many states at once.
    The batched questions use cuRobo v0.7.8's MotionGen directly, as the GPU
    tests do: the planner answers them one state at a time."""

    def __init__(self):
        stack.core()
        from rammp_curobo import CuRoboPlanner
        from rammp_curobo.urdf_model import prepare_urdf, write_urdf

        # the model the planner nodes are given on /arm/robot_description
        self._model_dir = tempfile.TemporaryDirectory()
        urdf = write_urdf(prepare_urdf(stack.arm_model()), self._model_dir.name)
        self.planner = CuRoboPlanner.from_config(stack.CONTROL_CONFIG, urdf_path=urdf)
        self.limits = self.planner.joint_limits()["position"]
        self.activation = self.planner.collision_activation_distance

    def push(self, world):
        """Plan in `world`, a path or a rammp_curobo Scene, from now on.
        Returns its padded boxes, as sphere_box_penetration takes them."""
        self.planner.update_world(world)
        return {
            box["name"]: {"dims": box["dims"], "pose": box["pose"]}
            for box in self.planner.world_boxes
        }

    def _tensor(self, states):
        """Joint vectors as one tensor in cuRobo's joint order, which it
        consumes them in: contiguous, as its kinematics kernel takes them."""
        p = self.planner
        order = [p.joint_names.index(name) for name in p._curobo_joint_names]
        return p._tensor(np.ascontiguousarray(states[:, order]))

    def feasible(self, states):
        """check_state_valid's verdict on each of `states`, (..., 7): (N,)."""
        from curobo.types.robot import JointState

        states = np.asarray(states, dtype=float).reshape(-1, 7)
        names = list(self.planner._curobo_joint_names)
        out = [np.zeros(0, dtype=bool)]
        for i in range(0, len(states), BATCH):
            q = self._tensor(states[i : i + BATCH])
            metrics = self.planner._motion_gen.check_constraints(
                JointState.from_position(q, joint_names=names)
            )
            out.append(metrics.feasible.view(-1).cpu().numpy().astype(bool))
        return np.concatenate(out)

    def kinematics(self, states):
        """(the tool's position (N, 3), the collision spheres (N, n, 4)) at each
        of `states`, (N, 7); a sphere cuRobo leaves out has a radius <= 0."""
        tools, spheres = [], []
        for i in range(0, len(states), BATCH):
            fk = self.planner._motion_gen.kinematics.get_state(
                self._tensor(states[i : i + BATCH])
            )
            tools.append(fk.ee_position.cpu().numpy().astype(float))
            spheres.append(fk.link_spheres_tensor.cpu().numpy().astype(float))
        return np.concatenate(tools), np.concatenate(spheres)


def chair_scene():
    """The chair planner's start-up world as a scene for the control planner:
    world_mebot.yaml, with gen3_mebot.yaml's layers beside its own."""
    layers, world = stack.chair_layers()
    from rammp_curobo.scene import Scene

    return Scene(
        world.base_frame,
        world.obstacles,
        world.targets,
        world.objects,
        layers=layers + world.layers,
    )


def pair_search(planner, model, search, present, absent, group, thresholds, box):
    """Seeded and capped: PAIRS pairs whose straight joint path the layer that
    world `present` adds to world `absent` blocks alone, and that takes the
    sim arm, posed along it in `model`, into contact group `group`.

    Returns ([{start, goal, crossing_mm}], what was tried, in words). Fails,
    naming what it tried, if fewer pairs are found."""
    from rammp_curobo.world import sphere_box_penetration

    rng = np.random.default_rng(search["seed"])
    states = rng.uniform(*box, size=(search["states"], 7))
    planner.push(present)
    pool = states[planner.feasible(states)]
    start, goal = sample_pairs(
        rng,
        pool,
        search["tries"],
        search["apart_rad"],
        turning(planner.limits),
        planner.limits,
    )
    paths = straight(start, goal, STEPS)
    blocked = ~planner.feasible(paths).reshape(len(paths), STEPS).all(axis=1)
    boxes = planner.push(absent)
    clear = planner.feasible(paths[blocked]).reshape(-1, STEPS).all(axis=1)
    pairs, near, depths = [], 0, []
    for i in np.nonzero(blocked)[0][clear]:
        # cuRobo's collision cost starts at the activation distance: a path
        # that keeps it from every box left gives a plan no reason to bend
        spheres = planner.kinematics(paths[i])[1]
        reach = spheres[spheres[..., 3] > 0] + [0.0, 0.0, 0.0, planner.activation]
        if sphere_box_penetration(reach, boxes):
            near += 1
            continue
        if len(depths) == search["measured"]:
            break
        deepest = deepest_contacts(model, densify(start[i], goal[i]))
        crossing = deepest.pop(group, 0.0)
        depths.append(crossing)
        if (
            crossing >= thresholds["crossing_mm"] / 1e3
            and max(deepest.values(), default=0.0) <= thresholds["elsewhere_mm"] / 1e3
        ):
            pairs.append(
                {"start": start[i], "goal": goal[i], "crossing_mm": crossing * 1e3}
            )
            if len(pairs) == PAIRS:
                break
    tried = (
        "seed %d: %d of %d states valid; of %d pairs, %d blocked, %d of them clear "
        "without the layer; of the %d of those looked at, %d come within the "
        "activation distance of what is left, and of the %d MuJoCo measured, %d go "
        "%g mm or deeper into the %s and no deeper than %g mm into anything else"
        % (
            search["seed"],
            len(pool),
            search["states"],
            len(start),
            blocked.sum(),
            clear.sum(),
            near + len(depths),
            near,
            len(depths),
            len(pairs),
            thresholds["crossing_mm"],
            group,
            thresholds["elsewhere_mm"],
        )
    )
    if len(pairs) < PAIRS:
        raise RuntimeError(
            "found %d of %d pairs (%s; the deepest of the paths measured %.1f mm)"
            % (len(pairs), PAIRS, tried, 1e3 * max(depths, default=0.0))
        )
    return pairs, tried


def reach_search(planner, search, world, box):
    """Seeded: the S3 start, the state valid in `world` whose tool is nearest
    search["start_tool"], and per region search["per_region"] goals valid
    there with their tool in the region, spread out (farthest-point
    sampling).

    Returns (start, its tool, [(region, goal, tool)], how many states were
    valid). Fails, naming the region, if one has too few."""
    rng = np.random.default_rng(search["seed"])
    states = rng.uniform(*box, size=(search["states"], 7))
    planner.push(world)
    pool = states[planner.feasible(states)]
    if not len(pool):
        raise RuntimeError(
            "no state of %d (seed %d) is valid with every layer on"
            % (search["states"], search["seed"])
        )
    tools = planner.kinematics(pool)[0]
    first = int(np.argmin(np.linalg.norm(tools - search["start_tool"], axis=1)))
    start = pool[first]
    wrapped = wrap(start, pool, turning(planner.limits))
    usable = ((wrapped >= planner.limits[0]) & (wrapped <= planner.limits[1])).all(
        axis=1
    )
    usable[first] = False  # the start is no goal
    goals = []
    for region, extent in search["regions"].items():
        low, high = np.array([extent[k] for k in "xyz"]).T
        index = np.nonzero(usable & ((tools >= low) & (tools <= high)).all(axis=1))[0]
        if len(index) < search["per_region"]:
            raise RuntimeError(
                "%d of the %d states valid with every layer on (seed %d) put the "
                "tool %s the chair (%s); %d are needed"
                % (
                    len(index),
                    len(pool),
                    search["seed"],
                    "in front of" if region == "front" else region,
                    extent,
                    search["per_region"],
                )
            )
        rng.shuffle(index)
        chosen = [index[0]]
        while len(chosen) < search["per_region"]:
            gap = np.linalg.norm(tools[index][:, None] - tools[chosen][None], axis=2)
            chosen.append(index[int(np.argmax(gap.min(axis=1)))])
        goals += [(region, wrapped[c], tools[c]) for c in chosen]
    return start, tools[first], goals, len(pool)


def _floats(values):
    """A YAML flow sequence of floats that reads back as the same numbers."""
    return "[%s]" % ", ".join(repr(float(v)) for v in values)


def generated(found):
    """The part of config/scenarios.yaml that find_pairs writes, from what the
    searches `found`: {digests, start, start_tool, reaches: {seed, states,
    valid, goals: [(region, goal, tool)]}, platform and person: {seed,
    posture, pairs: [{start, goal, crossing_mm}]}}."""
    reaches = found["reaches"]
    lines = [
        "# Rerun find_pairs whenever the layers change: run_suite refuses",
        "# requests found with other layer files than the committed ones.",
        "",
        "# sha256 of the layer files they were found with",
        "layers_sha256:",
    ]
    lines += ["  %s: %s" % item for item in sorted(found["digests"].items())]
    lines += [
        "",
        "# Where the sim arm starts, and goes back to on /mebot_sim/reset, and",
        "# where the S3 reaches start: a state valid with every layer on, its",
        "# tool_frame at (%.3f, %.3f, %.3f), beside the chair on the arm's own"
        % tuple(found["start_tool"]),
        "# side. The bench retract is no such start: it is inside the padded",
        "# person layer.",
        "start: %s" % _floats(found["start"]),
        "",
        "# S3: joint goals valid with every layer on (%d of %d states, seed %d),"
        % (reaches["valid"], reaches["states"], reaches["seed"]),
        "# their tools spread out in front of the chair and beside it.",
        "reaches:",
        "  seed: %d" % reaches["seed"],
        "  goals:",
    ]
    lines += [
        "    - %s  # %s: tool at (%.3f, %.3f, %.3f)" % (_floats(goal), region, *tool)
        for region, goal, tool in reaches["goals"]
    ]
    about = {
        "platform": [
            "# S1: start and goal valid with the floor and the platform; the",
            "# straight joint path between them blocked by the platform alone, and",
            "# crossing_mm into the true MEBot in MuJoCo, with the chair empty.",
        ],
        "person": [
            "# S2: start and goal valid with every layer on; the straight joint",
            "# path between them blocked by the person layer alone, and",
            "# crossing_mm into the stand-in in MuJoCo, seated in `posture`.",
        ],
    }
    for key in ("platform", "person"):
        found_pairs = found[key]
        lines += [""] + about[key]
        lines += [
            "%s_pairs:" % key,
            "  seed: %d" % found_pairs["seed"],
            "  posture: %s" % (found_pairs["posture"] or "none"),
            "  pairs:",
        ]
        for pair in found_pairs["pairs"]:
            lines += [
                "    - start: %s" % _floats(pair["start"]),
                "      goal: %s" % _floats(pair["goal"]),
                "      crossing_mm: %.1f" % pair["crossing_mm"],
            ]
    return "\n".join(lines) + "\n"


def hand_written(text):
    """The hand-written part of the scenarios file `text`, everything above
    MARKER (all of it without one), and what it holds. A key find_pairs
    writes is refused there: YAML keeps the last of two equal keys, and
    would keep it silently."""
    head = re.split(r"^%s$" % re.escape(MARKER), text, maxsplit=1, flags=re.M)[0]
    data = yaml.safe_load(head) or {}
    clash = [key for key in GENERATED if key in data]
    if clash:
        raise ValueError(
            "config/scenarios.yaml holds %s above the part find_pairs writes, "
            "which holds it as well" % ", ".join(repr(key) for key in clash)
        )
    return head, data


def compose(text, generated_part):
    """The scenarios file `text` with what find_pairs wrote in it replaced by
    `generated_part`, its hand-written part kept as it is."""
    head, _ = hand_written(text)
    return head.rstrip("\n") + "\n\n" + MARKER + "\n" + generated_part


def _write(path, text):
    """Replace `path` with `text` in one step: no reader sees half a file."""
    partial = "%s.%d.tmp" % (path, os.getpid())
    with open(partial, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(partial, path)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--menagerie",
        default=scene.MENAGERIE,
        help="a mujoco_menagerie checkout (default: %(default)s)",
    )
    parser.add_argument(
        "--humanoid",
        default=scene.HUMANOID,
        help="the DeepMind humanoid the stand-in is posed from",
    )
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    path = stack.config("scenarios.yaml")
    try:
        text = path.read_text(encoding="utf-8")
        thresholds = hand_written(text)[1]["thresholds"]
        assets = scene.Assets(args.menagerie, args.humanoid)
        print("building this checkout's planner on the GPU...", flush=True)
        planner = Planner()
        chair = chair_scene()
        worlds = stack.worlds()
        floor, floor_platform = worlds["floor_only"][1], worlds["no_person"][1]
        empty = scene.build(assets, PLATFORM["posture"])
        box = search_box(empty, planner.limits)
        found = {"digests": stack.layer_digests()}
        for key, search, present, absent, model, group in (
            ("platform", PLATFORM, floor_platform, floor, empty, "mebot"),
            (
                "person",
                PERSON,
                chair,
                floor_platform,
                scene.build(assets, PERSON["posture"]),
                "standin",
            ),
        ):
            pairs, tried = pair_search(
                planner, model, search, present, absent, group, thresholds, box
            )
            found[key] = dict(search, pairs=pairs)
            print(
                "%s pairs (%s): %s mm"
                % (
                    key,
                    tried,
                    ", ".join("%.1f" % pair["crossing_mm"] for pair in pairs),
                ),
                flush=True,
            )
        start, tool, goals, valid = reach_search(planner, REACHES, chair, box)
        found.update(
            start=start,
            start_tool=tool,
            reaches=dict(REACHES, valid=valid, goals=goals),
        )
        print(
            "reaches (seed %d): %d of %d states valid with every layer on; the start's "
            "tool at (%.3f, %.3f, %.3f); goals' tools %s"
            % (
                REACHES["seed"],
                valid,
                REACHES["states"],
                *tool,
                "; ".join(
                    "%s (%.2f, %.2f, %.2f)" % (region, *at) for region, _, at in goals
                ),
            ),
            flush=True,
        )
        _write(path, compose(text, generated(found)))
    except (OSError, ValueError, KeyError, RuntimeError) as exc:
        print("find_pairs: %s: %s" % (type(exc).__name__, exc), file=sys.stderr)
        return 1
    print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
